/**
 * 「读者插进来的引导」当前该显示成哪一态（**纯显示**，不改任何排队/steering 行为 ✗）。
 *
 * 用户看到的现象与它的真实语义：引导交给引擎后，引擎会在**下一个安全点**读取它 —— 通常就是
 * **当前工具调用结束之后** ✓（用户原话："每次都是工具调用结束之后才加入对话" ✓）。
 * 所以在那之前显示"已加入"是**误导** ✗。
 *
 * **所选信号**（现有信号，不新增标记 ✓）：该会话此刻**是否有正在跑的工具**
 * （`role === 'tool' && status === 'running'` —— `ChatPage.tsx:625` 的 `queuedGuidanceAwaitingTool`
 *  用的就是它 ✓）。理由：
 *  - 它**正是**用户观察到的那个边界（工具结束 ⇒ 才加入）✓；
 *  - 它**已经存在**且已被别处使用 ✓（不新造状态 ✗）；
 *  - 引擎读取引导的时机是"**下一个安全点**"✓，而"工具还在跑"是唯一能从渲染层观测到的
 *    "还没到安全点"的证据 ✓。
 * 局限（如实写 ✓）：若某轮**没有工具**（纯文本回合）✓，则没有"等待中"可言 ✓ ⇒ 直接按"已加入"显示 ✓
 * （这也符合实际：没有工具时引擎会立刻进入安全点 ✓）。
 */

export type GuidanceDisplayState = 'waiting' | 'joined'

/**
 * `toolRunning` = 该会话此刻是否有正在跑的工具（由调用方从消息里判定 ✓）。
 * 只要它还在跑 ✓ ⇒ 已插入的引导都算**等待中** ✓；工具跑完 ⇒ 显示**已加入** ✓。
 */
export function guidanceDisplayState(toolRunning: boolean): GuidanceDisplayState {
  return toolRunning ? 'waiting' : 'joined'
}

